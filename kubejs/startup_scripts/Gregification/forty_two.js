GTCEuStartupEvents.registry('gtceu:machine', allthemods => {
    allthemods.create('digital_generator', 'multiblock')
        .rotationState(RotationState.NON_Y_AXIS)
        .recipeTypes('digit_generator')
        .appearanceBlock(() => Block.getBlock('gtceu:segment_casing'))
        .recipeModifiers([GTRecipeModifiers.PARALLEL_HATCH, GTRecipeModifiers.OC_NON_PERFECT])
        .pattern(definition => FactoryBlockPattern.start()
            .aisle('VVVVV', 'V   V', 'V   V', 'VVVVV', 'V   V', 'V   V', 'VVVVV')
            .aisle('AAAAA', 'A   A', 'A   A', 'AAAAA', 'A   A', 'A   A', 'AAAAA')
            .aisle('GGGGG', 'G   G', 'G   G', 'GGKGG', 'G   G', 'G   G', 'GGGGG')
            .where('K', Predicates.controller(Predicates.blocks(definition.get())))
            .where('V', Predicates.blocks('gtceu:computer_heat_vent'))
            .where('A', Predicates.blocks('gtceu:advanced_computer_casing'))
            .where('G', Predicates.blocks('gtceu:segment_casing')
                .or(Predicates.autoAbilities(definition.getRecipeTypes()))
                .or(Predicates.abilities(PartAbility.MAINTENANCE).setExactLimit(1))
                .or(Predicates.abilities(PartAbility.PARALLEL_HATCH).setMaxGlobalLimited(1))
            )
            .where(' ', Predicates.any())
            .build()
        )
        .workableCasingModel(
            'gtceu:block/casings/segment_casing/segment_casing',
            'gtceu:block/multiblock/digital_generator'
        )

    allthemods.create('alu', 'multiblock')
        .rotationState(RotationState.NON_Y_AXIS)
        .recipeTypes('alu')
        .appearanceBlock(() => Block.getBlock('gtceu:advanced_computer_casing'))
        .machine((holder) => new CoilWorkableElectricMultiblockMachine(holder))
        .recipeModifiers([GTRecipeModifiers.PARALLEL_HATCH, GTRecipeModifiers.OC_PERFECT])
        .pattern(definition => FactoryBlockPattern.start()
            .aisle('AAAAA', 'ACCCA', 'ACCCA', 'ACCCA', 'AAAAA')
            .aisle('ACCCA', 'CLLLC', 'C   C', 'CLLLC', 'ACCCA')
            .aisle('ACCCA', 'VLLLV', 'V   V', 'VLLLV', 'ACCCA')
            .aisle('ACCCA', 'CLLLC', 'C   C', 'CLLLC', 'ACCCA')
            .aisle('AAAAA', 'AFFFA', 'AFKFA', 'AFFFA', 'AAAAA')
            .where('K', Predicates.controller(Predicates.blocks(definition.get())))
            .where('A', Predicates.blocks('gtceu:advanced_computer_casing'))
            .where('C', Predicates.blocks('gtceu:computer_casing'))
            .where('V', Predicates.blocks('gtceu:computer_heat_vent'))
            .where('L', Predicates.heatingCoils())
            .where('F', Predicates.blocks('gtceu:computer_casing')
                .or(Predicates.autoAbilities(definition.getRecipeTypes()))
                .or(Predicates.abilities(PartAbility.MAINTENANCE).setExactLimit(1))
                .or(Predicates.abilities(PartAbility.PARALLEL_HATCH).setMaxGlobalLimited(1))
            )
            .where(' ', Predicates.any())
            .build()
        )
        .workableCasingModel(
            'gtceu:block/casings/hpca/advanced_computer_casing/side',
            'gtceu:block/multiblock/alu'
        )

    allthemods.create('numeric_compressor', 'multiblock')
        .rotationState(RotationState.NON_Y_AXIS)
        .recipeTypes('numeric_compressor')
        .appearanceBlock(() => Block.getBlock('gtceu:computer_casing'))
        .recipeModifiers([GTRecipeModifiers.PARALLEL_HATCH, GTRecipeModifiers.OC_NON_PERFECT])
        .pattern(definition => FactoryBlockPattern.start()
            .aisle('CCC', 'CCC', 'CVC', 'CCC', 'AAA')
            .aisle('CCC', 'C C', 'V V', 'CAC', 'AAA')
            .aisle('FFF', 'FKC', 'CVC', 'CCC', 'AAA')
            .where('K', Predicates.controller(Predicates.blocks(definition.get())))
            .where('A', Predicates.blocks('gtceu:advanced_computer_casing'))
            .where('C', Predicates.blocks('gtceu:computer_casing'))
            .where('V', Predicates.blocks('gtceu:computer_heat_vent'))
            .where('F', Predicates.blocks('gtceu:computer_casing')
                .or(Predicates.autoAbilities(definition.getRecipeTypes()))
                .or(Predicates.abilities(PartAbility.MAINTENANCE).setExactLimit(1))
                .or(Predicates.abilities(PartAbility.PARALLEL_HATCH).setMaxGlobalLimited(1))
            )
            .where(' ', Predicates.any())
            .build()
        )
        .workableCasingModel(
            'gtceu:block/casings/hpca/computer_casing/side',
            'gtceu:block/multiblock/numeric_compressor'
        )

    allthemods.create('deep_thought', 'multiblock')
        .rotationState(RotationState.NON_Y_AXIS)
        .recipeTypes('deep_thought')
        .appearanceBlock(() => Block.getBlock('gtceu:advanced_computer_casing'))
        .recipeModifiers([GTRecipeModifiers.OC_NON_PERFECT])
        .pattern(definition => FactoryBlockPattern.start()
            .aisle('ACCCCCA', 'ACCCCCA', 'ACCCCCA', 'ACCCCCA', 'AVVVVVA')
            .aisle('ACCCCCA', 'A     A', 'A     A', 'A     A', 'ACCCCCA')
            .aisle('AFFFFCA', 'APPKPPA', 'APDDDPA', 'APDDDPA', 'AVVVVVA')
            .where('K', Predicates.controller(Predicates.blocks(definition.get())))
            .where('A', Predicates.blocks('gtceu:advanced_computer_casing'))
            .where('C', Predicates.blocks('gtceu:computer_casing'))
            .where('V', Predicates.blocks('gtceu:computer_heat_vent'))
            .where('P', Predicates.blocks('gtceu:panel_casing'))
            .where('D', Predicates.blocks('gtceu:display_casing'))
            .where('F', Predicates.blocks('gtceu:computer_casing')
                .or(Predicates.autoAbilities(definition.getRecipeTypes()))
                .or(Predicates.abilities(PartAbility.MAINTENANCE).setExactLimit(1))
            )
            .where(' ', Predicates.any())
            .build()
        )
        .workableCasingModel(
            'gtceu:block/casings/hpca/advanced_computer_casing/side',
            'gtceu:block/multiblock/deep_thought'
        )
})

